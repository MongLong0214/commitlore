#!/usr/bin/env node
// T-704 / #590: generated README facts must stay honest about their scope.
//
// This is the one CI checker for generated/checkable README facts. It owns only
// the entries named in OWNED_FACTS below. In particular, it does NOT own rates,
// timings, run counts, or other numeric prose outside the benchmark block and
// the two guarded headline summaries. Those facts must not be described as
// machine-guarded merely because this file exists.
//
// The owned facts are read from their product sources at check time, then checked
// in both the English and Korean READMEs. The benchmark block is additionally
// regenerated byte-for-byte in every public README.
//
// Usage:
//   node scripts/check-readme-numbers.mjs [--write] [--readme <path>] [--facts-readme <path>]... [<results.jsonl>...]
//
// With no result files it checks the sources declared in bench/report.ts
// (README_SOURCES) — which is what CI runs. `--write` replaces a generated block
// only after the provenance gate passes.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const PUBLIC_READMES = ['README.md', 'README.ko.md', 'README.ja.md', 'README.zh-CN.md'].map((file) =>
  path.join(REPO_ROOT, file),
);
const WITHDRAWAL_MARKER = '<!-- BENCH:WITHDRAWN -->';
const GENERATED_BEGIN = '<!-- BENCH:BEGIN -->';
const GENERATED_END = '<!-- BENCH:END -->';

/**
 * This declaration is the complete contract. Do not add prose-looking facts to
 * the README and imply that this checker owns them unless they are added here
 * with a source and a check below.
 */
const OWNED_FACTS = Object.freeze([
  'release version in English and Korean install pins (package.json)',
  'Node.js floor in English and Korean prerequisites and docs/COMPATIBILITY.md (package.json)',
  'headline re-proposal counts, denominators, rates, and analysis-set size in English and Korean (bench/report.ts)',
  'Provenance value grammar in English and Korean protocol tables (src/core/types.ts)',
  'the generated BENCH block in every public README (bench/report.ts)',
]);
const FACT_README_DEFAULTS = ['README.md', 'README.ko.md'].map((file) => path.join(REPO_ROOT, file));

const usage = () => {
  process.stderr.write(
    'usage: check-readme-numbers.mjs [--write] [--readme <path>] [--facts-readme <path>]... [<results.jsonl>...]\n' +
    '  --readme  one markdown file to check (default: all four public READMEs)\n' +
    '  --facts-readme  English then Korean README for the fact contract (default: README.md, README.ko.md)\n' +
    '  --write   regenerate the block in place instead of only checking it\n',
  );
  return 2;
};

const parseArgs = (argv) => {
  const files = [];
  const factsReadmes = [];
  let readme = null;
  let write = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--write') {
      write = true;
      continue;
    }
    if (arg === '--readme') {
      const value = argv[i + 1];
      if (value === undefined) return null;
      readme = path.resolve(REPO_ROOT, value);
      i += 1;
      continue;
    }
    if (arg === '--facts-readme') {
      const value = argv[i + 1];
      if (value === undefined) return null;
      factsReadmes.push(path.resolve(REPO_ROOT, value));
      i += 1;
      continue;
    }
    if (arg.startsWith('--')) return null;
    files.push(arg);
  }
  return { factsReadmes, readme, files, write };
};

/**
 * Runs the generator in a child process rather than importing it.
 *
 * `bench/report.ts` is TypeScript, and this script has to run on the Node floor
 * the package declares (>=22), where type stripping is not on by default. The
 * flag is accepted on every supported version; importing the module directly is
 * not.
 */
const regenerate = (files) => {
  const result = spawnSync(
    process.execPath,
    ['--experimental-strip-types', '--no-warnings=ExperimentalWarning', 'bench/report.ts', ...files, '--section'],
    { cwd: REPO_ROOT, encoding: 'utf8' },
  );
  if (result.error) {
    process.stderr.write(`check-readme-numbers: could not run bench/report.ts — ${result.error.message}\n`);
    return null;
  }
  if (result.status !== 0) {
    if (/\bunrecorded:\s*\d+/.test(result.stderr)) {
      return { expected: null, provenanceRecorded: false };
    }
    process.stderr.write(result.stderr || '');
    process.stderr.write(`check-readme-numbers: bench/report.ts exited ${result.status}\n`);
    return null;
  }
  return { expected: result.stdout, provenanceRecorded: true };
};

/**
 * Statistics that have no business appearing outside the generated block. Kept
 * deliberately short: each pattern is a shape that only ever comes out of the
 * benchmark, so a hit is a hand-written number rather than ordinary prose.
 */
const STRAY_STATISTIC_PATTERNS = [
  { label: 'a p-value', pattern: /\bp\s*=\s*[0-9.]/ },
  { label: 'a percentage-point figure', pattern: /\d+(?:\.\d+)?\s?pp\b/ },
  { label: 'an odds ratio', pattern: /odds ratio/i },
  { label: 'a Fisher test result', pattern: /Fisher exact/i },
];

const firstDifference = (expected, actual) => {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  for (let i = 0; i < Math.max(expectedLines.length, actualLines.length); i += 1) {
    if (expectedLines[i] !== actualLines[i]) {
      return { line: i + 1, expected: expectedLines[i] ?? '(no such line)', actual: actualLines[i] ?? '(no such line)' };
    }
  }
  return null;
};

const relativePath = (file) => {
  const inside = path.relative(REPO_ROOT, file);
  return inside !== '' && !inside.startsWith('..') ? inside : file;
};

const findStrays = (markdown) =>
  STRAY_STATISTIC_PATTERNS.filter(({ pattern }) => pattern.test(markdown));

const failClosed = (message) => {
  process.stderr.write(`check-readme-numbers: ${message}\n`);
  return null;
};

/** Read facts only from the product sources named in OWNED_FACTS. */
const sourceFacts = (generatedSection) => {
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf8'));
  } catch (error) {
    return failClosed(`could not read package.json — ${error.message}`);
  }
  if (typeof pkg.version !== 'string' || typeof pkg.engines?.node !== 'string') {
    return failClosed('package.json must declare string version and engines.node values');
  }
  const nodeFloor = pkg.engines.node.match(/^>=(\d+\.\d+\.\d+)$/)?.[1];
  if (nodeFloor === undefined) return failClosed(`unsupported engines.node format: ${pkg.engines.node}`);

  const provenanceSource = fs.readFileSync(path.join(REPO_ROOT, 'src', 'core', 'types.ts'), 'utf8');
  const provenanceDeclaration = provenanceSource.match(
    /export const PROVENANCE_PREFIXES\s*=\s*\[([^\]]+)\]\s+as const;/,
  )?.[1];
  const provenance = provenanceDeclaration === undefined
    ? []
    : [...provenanceDeclaration.matchAll(/'([^']+)'/g)].map((match) => match[1]);
  if (provenance.length === 0) return failClosed('could not read PROVENANCE_PREFIXES from src/core/types.ts');
  const provenanceGrammar = provenance.map((value) => (value === 'inherited' ? 'inherited <sha>' : value));

  const analysisSet = generatedSection.match(/\*\*Analysis set — ([\d,]+) of \d+ rows\*\*/)?.[1];
  const analysisStart = generatedSection.indexOf('**Analysis set —');
  const significanceStart = generatedSection.indexOf('**Significance:**');
  const analysisSection = analysisStart === -1 || significanceStart === -1
    ? ''
    : generatedSection.slice(analysisStart, significanceStart);
  const analysisRows = [...analysisSection.matchAll(
    /^\| `commitlore-(off|on)` \| (\d+) \| (\d+) \| ([\d.]+) \|/gm,
  )];
  const arms = Object.fromEntries(
    analysisRows.map(([, arm, denominator, numerator, rate]) => [
      arm,
      { denominator: Number(denominator), numerator: Number(numerator), rate: `${(Number(rate) * 100).toFixed(1)}%` },
    ]),
  );
  if (analysisSet === undefined || arms.off === undefined || arms.on === undefined) {
    return failClosed('could not read the analysis-set headline from bench/report.ts');
  }
  if (Number(analysisSet.replaceAll(',', '')) !== arms.off.denominator + arms.on.denominator) {
    return failClosed('bench/report.ts analysis-set size does not equal its two arm denominators');
  }

  return {
    nodeFloor,
    provenanceGrammar,
    version: pkg.version,
    headline: { analysisSet, off: arms.off, on: arms.on },
  };
};

const headlineText = ({ analysisSet, off, on }) =>
  `analysis set ${String(analysisSet).replaceAll(',', '')}; commitlore-on ${on.numerator}/${on.denominator} (${on.rate}); ` +
  `commitlore-off ${off.numerator}/${off.denominator} (${off.rate})`;

const readHeadline = (file, markdown) => {
  const isKorean = path.basename(file) === 'README.ko.md';
  const match = isKorean
    ? markdown.match(
      /분석 집합 ([\d,]+)회에서[\s\S]{0,240}?\*\*(\d+\.\d+)%\*\* \((\d+)\/(\d+)\)에서[\s\S]{0,240}?\*\*(\d+\.\d+)%\*\* \((\d+)\/(\d+)\)/,
    )
    : markdown.match(
      /Across ([\d,]+) registered runs,[\s\S]{0,240}?\*\*(\d+\.\d+)%\*\* of them \((\d+)\/(\d+)\)\. Without them: \*\*(\d+\.\d+)%\*\* \((\d+)\/(\d+)\)/,
    );
  if (match === null) return null;
  const [, analysisSet, firstRate, firstNumerator, firstDenominator, secondRate, secondNumerator, secondDenominator] = match;
  const onFirst = !isKorean;
  const on = onFirst
    ? { denominator: Number(firstDenominator), numerator: Number(firstNumerator), rate: `${firstRate}%` }
    : { denominator: Number(secondDenominator), numerator: Number(secondNumerator), rate: `${secondRate}%` };
  const off = onFirst
    ? { denominator: Number(secondDenominator), numerator: Number(secondNumerator), rate: `${secondRate}%` }
    : { denominator: Number(firstDenominator), numerator: Number(firstNumerator), rate: `${firstRate}%` };
  return { analysisSet, off, on };
};

const sameHeadline = (actual, expected) =>
  actual !== null && headlineText(actual) === headlineText(expected);

const readEnglishHeadlineTable = (markdown) => {
  const match = markdown.match(
    /\| the agent alone \| \*\*(\d+\.\d+)%\*\* \((\d+)\/(\d+)\) \|\n\| \*\*with CommitLore\*\* \| \*\*(\d+\.\d+)%\*\* \((\d+)\/(\d+)\) \|/,
  );
  if (match === null) return null;
  const [, offRate, offNumerator, offDenominator, onRate, onNumerator, onDenominator] = match;
  return {
    off: { denominator: Number(offDenominator), numerator: Number(offNumerator), rate: `${offRate}%` },
    on: { denominator: Number(onDenominator), numerator: Number(onNumerator), rate: `${onRate}%` },
  };
};

const checkFactContract = (factsReadmes, facts) => {
  if (factsReadmes.length !== 2) {
    process.stderr.write('check-readme-numbers: fact contract requires exactly English then Korean --facts-readme paths.\n');
    return false;
  }
  const [englishPath, koreanPath] = factsReadmes;
  const readmes = [englishPath, koreanPath].map((file) => ({ file, relative: relativePath(file), markdown: fs.readFileSync(file, 'utf8') }));
  const [english, korean] = readmes;
  let valid = true;

  for (const { relative, markdown } of readmes) {
    const versions = markdown.match(/\bv\d+\.\d+\.\d+\b/g) ?? [];
    if (versions.length === 0 || versions.some((value) => value !== `v${facts.version}`)) {
      process.stderr.write(`${relative}: guarded release pins must all be v${facts.version} from package.json.\n`);
      valid = false;
    }
  }

  for (const { relative, markdown } of readmes) {
    const declaredFloors = [...markdown.matchAll(/Node\.js(?:-%3E%3D|\s+)(\d+\.\d+\.\d+)/g)].map((match) => match[1]);
    if (declaredFloors.length !== 3 || declaredFloors.some((floor) => floor !== facts.nodeFloor)) {
      process.stderr.write(`${relative}: guarded Node.js badge (alt and URL) and prerequisite must state ${facts.nodeFloor} from package.json.\n`);
      valid = false;
    }
  }
  const compatibility = fs.readFileSync(path.join(REPO_ROOT, 'docs', 'COMPATIBILITY.md'), 'utf8');
  if (!compatibility.includes(`| Node.js ≥ ${facts.nodeFloor} |`)) {
    process.stderr.write(`docs/COMPATIBILITY.md: guarded Node.js prerequisite must state ${facts.nodeFloor} from package.json.\n`);
    valid = false;
  }

  const headlines = readmes.map(({ file, markdown }) => readHeadline(file, markdown));
  if (!sameHeadline(headlines[0], facts.headline) || !sameHeadline(headlines[1], facts.headline)) {
    process.stderr.write(
      `${english.relative} and ${korean.relative}: guarded headline metrics must both equal bench/report.ts.\n` +
        `  generated: ${headlineText(facts.headline)}\n` +
        `  ${english.relative}: ${headlines[0] === null ? 'headline not found' : headlineText(headlines[0])}\n` +
        `  ${korean.relative}: ${headlines[1] === null ? 'headline not found' : headlineText(headlines[1])}\n`,
    );
    valid = false;
  }
  const englishTable = readEnglishHeadlineTable(english.markdown);
  const expectedTable = { off: facts.headline.off, on: facts.headline.on };
  if (
    englishTable === null ||
    englishTable.off.denominator !== expectedTable.off.denominator ||
    englishTable.off.numerator !== expectedTable.off.numerator ||
    englishTable.off.rate !== expectedTable.off.rate ||
    englishTable.on.denominator !== expectedTable.on.denominator ||
    englishTable.on.numerator !== expectedTable.on.numerator ||
    englishTable.on.rate !== expectedTable.on.rate
  ) {
    process.stderr.write(
      `${english.relative}: guarded headline table must equal bench/report.ts (${headlineText(facts.headline)}).\n`,
    );
    valid = false;
  }

  const expectedGrammar = facts.provenanceGrammar.join(' | ');
  for (const { relative, markdown } of readmes) {
    const provenanceRow = markdown.match(/^\| `Provenance:` \| (.+) \|$/m)?.[1];
    const actualGrammar = provenanceRow === undefined
      ? undefined
      : [...provenanceRow.matchAll(/`([^`]+)`/g)].map((match) => match[1]).join(' | ');
    if (actualGrammar !== expectedGrammar) {
      process.stderr.write(
        `${relative}: guarded Provenance grammar must list every src/core/types.ts value.\n` +
          `  product: ${expectedGrammar}\n` +
          `  README: ${actualGrammar ?? 'Provenance row not found'}\n`,
      );
      valid = false;
    }
  }

  if (valid) {
    process.stdout.write(`README fact contract matches: ${OWNED_FACTS.join('; ')}\n`);
  }
  return valid;
};

const main = () => {
  const args = parseArgs(process.argv.slice(2));
  if (args === null) return usage();

  const generation = regenerate(args.files);
  if (generation === null) return 1;

  const readmePaths = args.readme === null ? PUBLIC_READMES : [args.readme];
  const readmes = [];
  for (const file of readmePaths) {
    if (!fs.existsSync(file)) {
      process.stderr.write(`check-readme-numbers: no such file: ${file}\n`);
      return 1;
    }
    readmes.push({ file, markdown: fs.readFileSync(file, 'utf8'), relative: relativePath(file) });
  }

  if (!generation.provenanceRecorded) {
    for (const { markdown, relative } of readmes) {
      const withdrawalCount = markdown.split(WITHDRAWAL_MARKER).length - 1;
      const hasGeneratedBlock = markdown.includes(GENERATED_BEGIN) || markdown.includes(GENERATED_END);
      if (withdrawalCount !== 1 || hasGeneratedBlock) {
        process.stderr.write(
          `${relative}: dataset provenance is unrecorded; expected exactly one withdrawal notice and no generated numbers block.\n`,
        );
        return 1;
      }
      const strays = findStrays(markdown);
      if (strays.length > 0) {
        process.stderr.write(
          `${relative}: found ${strays.map(({ label }) => label).join(', ')} while benchmark numbers are withdrawn.\n`,
        );
        return 1;
      }
    }
    if (!args.write) {
      process.stdout.write(
        `${readmes.map(({ relative }) => relative).join(', ')}: withdrawal notice present; declared datasets lack provenance\n`,
      );
    }
    return 0;
  }

  for (const { markdown, relative } of readmes) {
    if (markdown.includes(WITHDRAWAL_MARKER)) {
      process.stderr.write(
        `${relative}: a provenanced dataset can be summarized, but the README still carries the withdrawal notice.\n`,
      );
      return 1;
    }
  }

  const expected = generation.expected;
  if (expected === null) return 1;
  const facts = sourceFacts(expected);
  if (facts === null) return 1;
  // A fixture passed through --readme exercises only the BENCH publication
  // state. Ordinary CI checks the public fact contract, and tests can opt into
  // it with two explicit --facts-readme paths.
  if ((args.readme === null || args.factsReadmes.length > 0) && !checkFactContract(
    args.factsReadmes.length === 0 ? FACT_README_DEFAULTS : args.factsReadmes,
    facts,
  )) return 1;
  const expectedLines = expected.replace(/\n$/, '').split('\n');
  // The markers are whatever the generator emits, read off its own output.
  const begin = expectedLines[0];
  const end = expectedLines[expectedLines.length - 1];
  const expectedBlock = expected.replace(/\n$/, '');
  for (const { file: readme, markdown, relative } of readmes) {
    const beginCount = markdown.split(begin).length - 1;
    const endCount = markdown.split(end).length - 1;
    if (beginCount !== 1 || endCount !== 1) {
      process.stderr.write(
        `${relative}: expected exactly one ${begin} ... ${end} block, found ${beginCount} begin and ${endCount} end markers.\n` +
          'A second block would let a stale copy of the numbers survive unnoticed.\n',
      );
      return 1;
    }
    const beginAt = markdown.indexOf(begin);
    const endAt = markdown.indexOf(end);
    if (endAt < beginAt) {
      process.stderr.write(`${relative}: ${end} appears before ${begin}.\n`);
      return 1;
    }
    const actual = markdown.slice(beginAt, endAt + end.length);
    if (args.write) {
      if (actual === expectedBlock) {
        process.stdout.write(`${relative}: already up to date, nothing written\n`);
      } else {
        fs.writeFileSync(readme, markdown.slice(0, beginAt) + expectedBlock + markdown.slice(endAt + end.length));
        process.stdout.write(
          `${relative}: block regenerated (${actual.split('\n').length} lines -> ${expectedBlock.split('\n').length} lines)\n`,
        );
      }
    } else if (actual !== expectedBlock) {
      const diff = firstDifference(expectedBlock, actual);
      process.stderr.write(
        `${relative}: the measured-results block does not match what bench/report.ts generates.\n\n` +
          (diff === null
            ? ''
            : `  first difference at line ${diff.line} of the block\n` +
              `  generated: ${diff.expected}\n` +
              `  in README: ${diff.actual}\n\n`) +
          `  README block: ${actual.split('\n').length} lines, ${actual.length} bytes\n` +
          `  generated:    ${expectedBlock.split('\n').length} lines, ${expectedBlock.length} bytes\n\n` +
          'Every number in that block comes from bench/results/ through bench/report.ts. Regenerate it:\n' +
          '  node --experimental-strip-types bench/report.ts --section\n' +
          'and paste the output between the markers, replacing the block entirely.\n',
      );
      return 1;
    }
    const outside = markdown.slice(0, beginAt) + markdown.slice(endAt + end.length);
    const strays = findStrays(outside);
    if (strays.length > 0) {
      process.stderr.write(
        `${relative}: found ${strays.map(({ label }) => label).join(', ')} outside the generated block.\n` +
          'Measured numbers belong between the markers, where they are regenerated and checked. Move it there,\n' +
          'or delete it if no log produces it.\n',
      );
      return 1;
    }
    if (!args.write) {
      process.stdout.write(
        `${relative}: measured-results block matches bench/report.ts (${expectedBlock.split('\n').length} lines, ${expectedBlock.length} bytes)\n`,
      );
    }
  }
  return 0;
};

process.exitCode = main();
